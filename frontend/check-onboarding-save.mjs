import { chromium } from "@playwright/test";
import { execFileSync } from "node:child_process";
import assert from "node:assert/strict";
import path from "node:path";

const root = path.resolve("..");
const base = "http://127.0.0.1:3013";
const code = execFileSync(path.join(root, "backend/.venv/bin/python"), ["-c", "from app.core.config import get_settings; print(get_settings().invite_code)"], { cwd: path.join(root, "backend"), encoding: "utf8" }).trim();
const browser = await chromium.launch({ channel: "chrome" });
const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
const page = await context.newPage();
const errors = [];
page.on("pageerror", error => errors.push(error.message));
await page.goto(`${base}/login?for=mother`);
await page.getByLabel("邀请码", { exact: true }).fill(code);
await page.getByRole("button", { name: "翻开我的回忆录" }).click();
await page.waitForURL("**/profiles?new=1&for=mother");
await page.getByLabel("怎么称呼这位家人", { exact: true }).fill("引导建档验收");
await page.getByRole("button", { name: "开始这本回忆录" }).click();
await page.waitForURL(/\/profiles\/[^/]+\/handoff$/);
const id = new URL(page.url()).pathname.split("/")[2];
await page.getByRole("heading", { name: "把手机交给引导建档验收" }).waitFor();
const saved = await context.request.get(`${base}/api/v1/profiles/${id}`);
assert.ok(saved.ok());
assert.equal((await saved.json()).elder_name, "引导建档验收");
await page.reload();
await page.getByRole("heading", { name: "把手机交给引导建档验收" }).waitFor();
await page.goto(base);
await page.waitForURL(`${base}/profiles/${id}`);
assert.equal(await page.locator(".chapter-row").count(), 0);
await page.goto(`${base}/welcome?step=5`);
await page.getByRole("link", { name: /为自己记录/ }).click();
await page.waitForURL("**/profiles?new=1&for=self");
await page.getByLabel("怎么称呼您", { exact: true }).fill("本人建档验收");
await page.getByRole("button", { name: "开始这本回忆录" }).click();
await page.waitForURL(/\/profiles\/[^/?]+$/);
await page.getByRole("link", { name: "开始第一次访谈" }).waitFor();
assert.deepEqual(errors, []);
await browser.close();
console.log("通过：隔离数据库中家属建档、交接、刷新读取、首页恢复、已登录本人建档；未调用模型。");
